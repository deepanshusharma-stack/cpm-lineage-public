"""Automation rules: a neutral schema, rule-set inventory and a one-line
plain-text rendering of each rule.

Three record types describe any rule-based bid / budget automation:

* ``Ruleset``: a named bundle of rules attached to campaigns
  (``entity_type="campaign"``) or to keyword bids (``entity_type="keyword"``).
* ``RulesetMember``: one (rule set, member) row.  The member id is a
  campaign id for campaign rule sets and a **bid id** for keyword rule sets.
  Adapters must supply current, non-deleted membership; duplicates are
  removed here but stale rows cannot be detected.
* ``Rule``: ``conditions`` and ``actions`` (JSON text or parsed objects).

Condition document: ``{"rules": [cond, ...]}`` where each ``cond`` is one of

=====================  ====================================================
time window            ``{"name": "time_range", "value": {"allowed_days":
                       [...], "start_time": "HH:MM", "end_time": "HH:MM"}}``
position targeting     ``{"position_targeting": true, "position_target": N
                       | {"min": a, "max": b}, "min_bid", "max_bid",
                       "guardrail_percentage", "guardrail_type",
                       "time_range"?}``
metric comparison      ``{"name" | "metric", "operator", "value" (scalar or
                       [lo, hi]), "days"?}``
=====================  ====================================================

Action document: ``[{"name": ..., "params": {"percentage", "value",
"guardrail_percentage", "min_limit", "max_limit"}}]``.

The key names are fields of ``RuleSchema`` so an adapter whose automation
product uses other names can map them without touching the logic.

Two guardrail notions exist and must not be confused: on a position-
targeting *condition* the guardrail percentage defines the bid ceiling
``base x (1 + g/100)`` (see ``guardrails``); on an *action* it is a parameter
of that step rule whose arithmetic is product specific and is only rendered
here, never evaluated.
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from typing import Any, Iterable, Mapping, Sequence

from ..schema import BidRecord, Entity
from ._util import norm_kw

__all__ = [
    "RuleSchema", "Ruleset", "Rule", "RulesetMember", "OPERATORS", "UNPARSED", "NO_RULE",
    "UNRESOLVED_BID", "parse_json", "ruleset_state", "select_rulesets", "dedupe_members",
    "rule_conditions", "position_conditions", "is_position_condition", "when_text",
    "rule_text", "assemble", "stats",
]

UNPARSED = "(unparsed rule)"      # rendering failed on a parsed document
NO_RULE = "—"                # the document was not parseable at all
UNRESOLVED_BID = "(unresolved bid id)"

OPERATORS: dict[str, str] = {
    "less_than_or_equal_to": "<=",
    "less_than": "<",
    "greater_than_or_equal_to": ">=",
    "greater_than": ">",
    "equal_to": "=",
    "not_equal_to": "!=",
    "in_between": "between",
}

_DAYS = ("mon", "tue", "wed", "thu", "fri", "sat", "sun")


@dataclass(frozen=True)
class RuleSchema:
    """Key names of the rule documents plus the two vocabulary sets."""

    rules_key: str = "rules"                       # list of conditions inside the condition document
    name_key: str = "name"                         # condition / action name
    metric_key: str = "metric"                     # alternative key carrying the metric name
    operator_key: str = "operator"
    value_key: str = "value"
    days_key: str = "days"                         # lookback length of a metric condition
    time_range_name: str = "time_range"            # name of a time-window condition (and key of an embedded one)
    position_flag: str = "position_targeting"      # truthy on a position-targeting condition
    position_target_key: str = "position_target"   # number, or {"min", "max"}
    min_bid_key: str = "min_bid"
    max_bid_key: str = "max_bid"
    guardrail_pct_key: str = "guardrail_percentage"
    guardrail_type_key: str = "guardrail_type"
    percentage_type: str = "percentage"            # guardrail type meaning "percent over the base bid"
    params_key: str = "params"
    # metrics read live (current state); every other metric is a lookback and gets "(last Nd)"
    live_metrics: frozenset[str] = frozenset(
        {"ad_position", "ad_rank", "organic_position", "organic_rank", "position", "status", "daily_budget"}
    )
    # rule names generated by the automation product itself; hidden from rendered config
    system_rule_names: frozenset[str] = frozenset({"sys_generated"})


@dataclass(frozen=True)
class Ruleset:
    """A named bundle of automation rules."""

    id: str
    name: str = ""
    entity_type: str = "keyword"          # "campaign" | "keyword"
    is_active: bool = True
    is_archived: bool = False
    is_template: bool = False
    is_deleted: bool = False
    advertiser_id: str | None = None
    start_date: Any = None
    updated_at: Any = None


@dataclass(frozen=True)
class Rule:
    """One rule of a rule set; ``conditions`` / ``actions`` are JSON text or parsed objects."""

    id: str
    ruleset_id: str
    name: str = ""
    conditions: Any = None
    actions: Any = None


@dataclass(frozen=True)
class RulesetMember:
    """Membership row: ``member_id`` is a campaign id or a bid id by rule-set type."""

    ruleset_id: str
    member_id: str


_BAD = object()


def parse_json(value: Any) -> Any:
    """Parse a JSON document that may already be parsed.

    Returns the object for a mapping / list, the decoded value for JSON
    text, ``None`` for ``None`` / empty text, and the module sentinel
    ``_BAD`` (compare with ``is``) for undecodable text.  Never raises.
    """
    if value is None:
        return None
    if isinstance(value, (Mapping, list, tuple)):
        return value
    if isinstance(value, (bytes, bytearray)):
        try:
            value = value.decode("utf-8")
        except Exception:
            return _BAD
    if isinstance(value, str):
        if not value.strip():
            return None
        try:
            return json.loads(value)
        except Exception:
            return _BAD
    return _BAD


def ruleset_state(ruleset: Ruleset) -> str:
    """State label: ``"Archived"`` if archived, else ``"Active"`` if active, else ``"Inactive"``."""
    if ruleset.is_archived:
        return "Archived"
    return "Active" if ruleset.is_active else "Inactive"


def select_rulesets(rulesets: Iterable[Ruleset], status: str = "active") -> list[Ruleset]:
    """Filter rule sets by status.

    Templates and deleted rule sets are always excluded.  ``"active"`` =
    active and not archived; ``"inactive"`` = everything else; ``"all"`` =
    both.  Raises ``ValueError`` on another status word.
    """
    if status not in ("active", "inactive", "all"):
        raise ValueError(f"status must be active, inactive or all, got {status!r}")
    out = []
    for rs in rulesets:
        if rs.is_template or rs.is_deleted:
            continue
        active = ruleset_state(rs) == "Active"
        if status == "all" or (status == "active") == active:
            out.append(rs)
    return out


def dedupe_members(members: Iterable[RulesetMember]) -> list[RulesetMember]:
    """Drop repeated (rule set, member) rows, keeping first-seen order."""
    seen: set[tuple[str, str]] = set()
    out = []
    for m in members:
        key = (str(m.ruleset_id), str(m.member_id))
        if key not in seen:
            seen.add(key)
            out.append(m)
    return out


def rule_conditions(conditions: Any, schema: RuleSchema | None = None) -> list[Mapping[str, Any]]:
    """The list of condition objects of a condition document.

    Accepts JSON text or a parsed object; a bare list is taken as the list
    itself.  Anything unparseable yields ``[]`` (never raises).
    """
    schema = schema or RuleSchema()
    doc = parse_json(conditions)
    if doc is None or doc is _BAD:
        return []
    if isinstance(doc, Mapping):
        doc = doc.get(schema.rules_key, [])
    if not isinstance(doc, (list, tuple)):
        return []
    return [c for c in doc if isinstance(c, Mapping)]


def is_position_condition(cond: Mapping[str, Any], schema: RuleSchema | None = None) -> bool:
    """True when the condition is a position-targeting configuration."""
    schema = schema or RuleSchema()
    return bool(cond.get(schema.position_flag))


def position_conditions(conditions: Any, schema: RuleSchema | None = None) -> list[Mapping[str, Any]]:
    """Position-targeting conditions of a condition document (``[]`` when none or unparseable)."""
    schema = schema or RuleSchema()
    return [c for c in rule_conditions(conditions, schema) if is_position_condition(c, schema)]


def _num(x: Any) -> str:
    if isinstance(x, bool):
        return str(x).lower()
    if isinstance(x, (int, float)):
        f = float(x)
        return str(int(f)) if f == int(f) else f"{f:g}"
    return str(x)


def _hhmm(t: Any, default: str) -> str:
    s = str(t).strip() if t not in (None, "") else default
    parts = s.split(":")
    if len(parts) >= 2 and parts[0].isdigit() and parts[1].isdigit():
        return f"{int(parts[0]):02d}:{int(parts[1]):02d}"
    return s


def when_text(value: Mapping[str, Any] | None) -> str:
    """Render a time window: ``daily 08:00–23:45`` or ``mon,wed 13:00–14:00``.

    "daily" when all seven days or none are listed; times default to
    ``00:00`` and ``23:59``.
    """
    value = value or {}
    days = [str(d).strip().lower()[:3] for d in (value.get("allowed_days") or [])]
    days = [d for d in _DAYS if d in days] + [d for d in days if d not in _DAYS]
    label = "daily" if not days or len(set(days)) >= 7 else ",".join(dict.fromkeys(days))
    return f"{label} {_hhmm(value.get('start_time'), '00:00')}–{_hhmm(value.get('end_time'), '23:59')}"


def _target_text(target: Any) -> str | None:
    if target is None:
        return None
    if isinstance(target, Mapping):
        return f"{_num(target.get('min'))}–{_num(target.get('max'))}"
    return f"<= {_num(target)}"


def _condition_text(cond: Mapping[str, Any], schema: RuleSchema) -> str:
    if is_position_condition(cond, schema):
        parts = []
        target = cond.get(schema.position_target_key)
        if target is not None:
            t = _target_text(target)
            parts.append(f"target position {t}")
        lo, hi = cond.get(schema.min_bid_key), cond.get(schema.max_bid_key)
        if lo is not None or hi is not None:
            parts.append(f"bid {_num(lo) if lo is not None else ''}–{_num(hi) if hi is not None else ''}")
        gp = cond.get(schema.guardrail_pct_key)
        if gp:
            parts.append(f"CPM guardrail {_num(gp)}%")
        tr = cond.get(schema.time_range_name)
        if isinstance(tr, Mapping):
            parts.append(when_text(tr.get(schema.value_key, tr) if isinstance(tr.get(schema.value_key), Mapping) else tr))
        return ", ".join(parts) if parts else "position targeting"
    name = cond.get(schema.name_key) or cond.get(schema.metric_key)
    if name == schema.time_range_name:
        v = cond.get(schema.value_key)
        return when_text(v if isinstance(v, Mapping) else None)
    name = str(name)
    op = str(cond.get(schema.operator_key))
    sym = OPERATORS.get(op, op.replace("_", " "))
    value = cond.get(schema.value_key)
    if isinstance(value, (list, tuple)):
        vtxt = " and ".join(_num(v) for v in value) if sym == "between" else ",".join(_num(v) for v in value)
    else:
        vtxt = _num(value)
    text = f"{name} {sym} {vtxt}"
    days = cond.get(schema.days_key)
    if days and name not in schema.live_metrics:
        text += f" (last {_num(days)}d)"
    return text


def _action_text(action: Mapping[str, Any], schema: RuleSchema) -> str:
    text = str(action.get(schema.name_key, "")).replace("_", " ").strip()
    params = action.get(schema.params_key) or {}
    if params.get("percentage") is not None:
        text += f" {_num(params['percentage'])}%"
    if params.get("value") is not None:
        text += f" {_num(params['value'])}"
    if params.get("guardrail_percentage") is not None:
        text += f" guardrail {_num(params['guardrail_percentage'])}%"
    if params.get("min_limit") is not None:
        text += f" min {_num(params['min_limit'])}"
    if params.get("max_limit") is not None:
        text += f" max {_num(params['max_limit'])}"
    return text.strip()


def rule_text(conditions: Any, actions: Any = None, schema: RuleSchema | None = None) -> str:
    """Render one rule as a readable line.

    Conditions are joined with ``AND``; the result is ``IF <conditions> THEN
    <actions>``.  With no actions the conditions alone are returned (for
    position targeting the condition *is* the configuration); with no
    conditions the actions alone.  Metric conditions on a lookback metric
    carry ``(last Nd)``; live metrics (``schema.live_metrics``) do not.

    Never raises: undecodable JSON gives ``"—"``, any other failure
    ``"(unparsed rule)"``.

    Examples::

        IF ad_rank > 20 AND daily 07:30–22:30 THEN increase bid 20% guardrail 140%
        target position 1–5, bid 200–5000, CPM guardrail 50%, sat,sun 07:00–23:00
    """
    schema = schema or RuleSchema()
    try:
        cdoc, adoc = parse_json(conditions), parse_json(actions)
        if cdoc is _BAD or adoc is _BAD:
            return NO_RULE
        conds = [_condition_text(c, schema) for c in rule_conditions(cdoc, schema)]
        if isinstance(adoc, Mapping):
            adoc = [adoc]
        acts = [_action_text(a, schema) for a in (adoc or []) if isinstance(a, Mapping)]
        conds = [c for c in conds if c]
        acts = [a for a in acts if a]
        ctxt, atxt = " AND ".join(conds), "; ".join(acts)
        if ctxt and atxt:
            return f"IF {ctxt} THEN {atxt}"
        return ctxt or atxt or NO_RULE
    except Exception:
        return UNPARSED


_STATE_ORDER = {"Active": 0, "Inactive": 1, "Archived": 2}


def assemble(
    rulesets: Iterable[Ruleset],
    members: Iterable[RulesetMember] = (),
    rules: Iterable[Rule] = (),
    *,
    bids: Iterable[BidRecord] = (),
    entities: Iterable[Entity] = (),
    status: str = "all",
    schema: RuleSchema | None = None,
) -> list[dict]:
    """Build the rule-set inventory.

    Per rule set (templates and deleted ones excluded, ``status`` filter as
    in ``select_rulesets``):

    * ``config`` = ``rule_text`` of each of its rules, system-generated
      rules skipped; rules attach only to their own rule set;
    * keyword rule set members resolve their bid id against ``bids`` ->
      ``{keyword, match_type, bid, base_bid, bid_id, entity_id, entity_name,
      entity_status}``; an unknown bid id renders the keyword as
      ``"(unresolved bid id)"``;
    * campaign rule set members -> ``{entity_id, name, status}`` sorted by name;
    * a rule set with no members still appears with empty lists;
    * ``n_entities`` = distinct campaign ids across both lists.

    Order: Active, Inactive, Archived; then type; then name (case-insensitive).

    Returns ``[{id, name, type, state, advertiser_id, updated, start, config,
    campaigns, keywords, n_entities}]``.
    """
    schema = schema or RuleSchema()
    ent = {e.entity_id: e for e in entities}
    bid_by_id = {str(b.bid_id): b for b in bids if b.bid_id is not None}
    mem: dict[str, list[str]] = {}
    for m in dedupe_members(members):
        mem.setdefault(str(m.ruleset_id), []).append(str(m.member_id))
    cfg_lines: dict[str, list[str]] = {}
    for r in rules:
        if r.name in schema.system_rule_names:
            continue
        cfg_lines.setdefault(str(r.ruleset_id), []).append(rule_text(r.conditions, r.actions, schema))
    out = []
    for rs in select_rulesets(rulesets, status):
        campaigns: list[dict] = []
        keywords: list[dict] = []
        for mid in mem.get(str(rs.id), []):
            if rs.entity_type == "campaign":
                e = ent.get(mid)
                campaigns.append({"entity_id": mid, "name": e.name if e else None, "status": e.status if e else None})
            else:
                b = bid_by_id.get(mid)
                e = ent.get(b.entity_id) if b else None
                keywords.append({
                    "keyword": norm_kw(b.targeting_unit) if b else UNRESOLVED_BID,
                    "match_type": b.match_type if b else None,
                    "bid": b.live_bid if b else None,
                    "base_bid": b.base_bid if b else None,
                    "bid_id": mid,
                    "entity_id": b.entity_id if b else None,
                    "entity_name": e.name if e else None,
                    "entity_status": e.status if e else None,
                })
        campaigns.sort(key=lambda c: (str(c["name"] or "").lower(), c["entity_id"]))
        keywords.sort(key=lambda k: (k["keyword"], str(k["entity_id"] or ""), k["bid_id"]))
        ids = {c["entity_id"] for c in campaigns} | {k["entity_id"] for k in keywords if k["entity_id"] is not None}
        out.append({
            "id": rs.id, "name": rs.name, "type": rs.entity_type, "state": ruleset_state(rs),
            "advertiser_id": rs.advertiser_id, "updated": rs.updated_at, "start": rs.start_date,
            "config": cfg_lines.get(str(rs.id), []),
            "campaigns": campaigns, "keywords": keywords, "n_entities": len(ids),
        })
    out.sort(key=lambda d: (_STATE_ORDER[d["state"]], str(d["type"]), str(d["name"]).lower(), str(d["id"])))
    return out


def stats(inventory: Sequence[Mapping[str, Any]]) -> dict[str, int]:
    """Counts over an ``assemble`` inventory.

    Returns ``{n, n_campaign_rulesets, n_keyword_rulesets, n_entities,
    n_keywords}`` where ``n_entities`` = distinct campaigns under any rule
    set and ``n_keywords`` = keyword x campaign member rows.
    """
    ids: set[Any] = set()
    for rs in inventory:
        ids |= {c["entity_id"] for c in rs["campaigns"]}
        ids |= {k["entity_id"] for k in rs["keywords"] if k["entity_id"] is not None}
    return {
        "n": len(inventory),
        "n_campaign_rulesets": sum(1 for rs in inventory if rs["type"] == "campaign"),
        "n_keyword_rulesets": sum(1 for rs in inventory if rs["type"] != "campaign"),
        "n_entities": len(ids),
        "n_keywords": sum(len(rs["keywords"]) for rs in inventory),
    }
